#include<bits/stdc++.h>
using namespace std;
int main()
{
	double a[100][100],b[100][100],tol;
	int i,j,k=1;
	
	cout<<"Enter the tolerance error"<<endl;
	cin>>tol;
	
	for(i=0;i<=4;i++)
	{
		a[i][0]=b[i][0]=0.0;
		a[i][4]=b[i][4]=12+(4-i);
	
	}
	
	for(j=0;j<=4;j++)
	{
		a[4][j]=b[4][j]=3*j;
		a[0][j]=b[0][j]=j*j;
	}
	
	a[2][2]=b[2][2]=0.25*(a[0][2]+a[4][2]+a[2][0]+a[2][4]);
	a[1][1]=a[1][1]=0.25*(a[0][0]+a[0][2]+a[2][2]+a[2][0]);
	a[1][3]=b[1][3]=0.25*(a[0][2]+a[0][4]+a[2][4]+a[2][2]);
	a[3][1]=b[3][1]=0.25*(a[2][0]+a[2][2]+a[4][0]+a[4][2]);
	a[3][3]=b[3][3]=0.25*(a[2][4]+a[2][2]+a[4][2]+a[4][4]);
	a[1][2]=b[1][2]=0.25*(a[0][2]+a[1][3]+a[2][2]+a[1][1]);
	a[2][1]=b[2][1]=0.25*(a[1][1]+a[2][2]+a[3][1]+a[2][0]);
	a[2][3]=b[2][3]=0.25*(a[2][2]+a[1][3]+a[2][4]+a[3][3]);
	a[3][2]=b[3][2]=0.25*(a[2][2]+a[3][3]+a[3][1]+a[4][2]);
	
	while(k!=0)
	{
		k=0;
		for(i=1;i<=3;i++)
		{
			for(j=1;j<=3;j++)
			{
				b[i][j]=0.25*(a[i-1][j]+a[i+1][j]+a[i][j-1]+a[i][j+1]);//five point start formula
				
				if(fabs(b[i][j]-a[i][j])>tol)
				{
					k=1;
					a[i][j]=b[i][j];
					
				}
				
			}
		}
	}
	
	for(i=0;i<=4;i++)
	{
		for(j=0;j<=4;j++)
		{
			cout<<a[i][j]<<" ";
		}
		cout<<endl;
	}
		
}
